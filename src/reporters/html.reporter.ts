import fs from 'fs';
import path from 'path';
import { AuditReport, Impact } from '../core/types';

function esc(text: string): string {
  return text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

const IMPACT_COLORS: Record<Impact, string> = {
  critical: '#f85149',
  serious: '#bc8cff',
  moderate: '#d29922',
  minor: '#8b949e',
};

export function generateHtmlReport(report: AuditReport, outputPath: string): void {
  const dir = path.dirname(outputPath);
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });

  const gradeColor =
    { A: '#3fb950', B: '#3fb950', C: '#d29922', D: '#d29922', F: '#f85149' }[report.grade] || '#8b949e';

  const pageRows = report.pages
    .map((p) => {
      const violations = p.violations
        .map(
          (v) => `
          <div class="violation">
            <span class="impact" style="color:${IMPACT_COLORS[v.impact]}">[${v.impact}]</span>
            <strong>${esc(v.help)}</strong> <span class="dim">(${esc(v.id)})</span>
            <div class="dim">${v.nodes.length} element(s) affected · <a href="${esc(v.helpUrl)}" target="_blank">Learn more</a></div>
            ${v.nodes
              .slice(0, 3)
              .map((n) => `<pre class="node-html">${esc(n.html)}</pre>`)
              .join('')}
            ${v.nodes.length > 3 ? `<div class="dim">... and ${v.nodes.length - 3} more</div>` : ''}
          </div>`,
        )
        .join('');

      const statusColor = p.violations.length === 0 ? '#3fb950' : '#f85149';
      return `
      <div class="card">
        <div class="card-header">
          <span style="color:${statusColor};font-weight:700">${p.violations.length === 0 ? 'PASS' : `${p.violations.length} VIOLATIONS`}</span>
          <strong>${esc(p.url)}</strong>
          <span class="dim">${p.passes} passes · ${p.scanDuration}ms</span>
        </div>
        ${violations ? `<div class="card-body">${violations}</div>` : ''}
      </div>`;
    })
    .join('');

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>Accessibility Audit Report</title>
<style>
  * { margin: 0; padding: 0; box-sizing: border-box; }
  body { font-family: -apple-system, BlinkMacSystemFont, sans-serif; background: #0d1117; color: #c9d1d9; padding: 24px; }
  .container { max-width: 1100px; margin: 0 auto; }
  h1 { color: #f0f6fc; margin-bottom: 4px; }
  .meta { color: #8b949e; font-size: 14px; margin-bottom: 24px; }
  .summary { display: flex; gap: 12px; margin-bottom: 24px; flex-wrap: wrap; }
  .stat { background: #161b22; border: 1px solid #30363d; border-radius: 8px; padding: 14px 20px; text-align: center; min-width: 100px; }
  .stat-value { font-size: 28px; font-weight: 700; }
  .stat-label { color: #8b949e; font-size: 11px; text-transform: uppercase; margin-top: 2px; }
  .card { background: #161b22; border: 1px solid #30363d; border-radius: 8px; margin-bottom: 16px; overflow: hidden; }
  .card-header { padding: 12px 16px; border-bottom: 1px solid #21262d; display: flex; align-items: center; gap: 12px; flex-wrap: wrap; }
  .card-body { padding: 12px 16px; }
  .violation { margin-bottom: 12px; padding-bottom: 12px; border-bottom: 1px solid #21262d; }
  .violation:last-child { border-bottom: none; margin-bottom: 0; padding-bottom: 0; }
  .impact { font-weight: 700; font-size: 12px; text-transform: uppercase; }
  .dim { color: #8b949e; font-size: 13px; }
  .node-html { background: #0d1117; border: 1px solid #21262d; border-radius: 4px; padding: 6px 10px; font-size: 12px; margin-top: 6px; overflow-x: auto; color: #f85149; }
  a { color: #58a6ff; }
  .footer { text-align: center; color: #484f58; font-size: 12px; margin-top: 24px; }
</style>
</head>
<body>
<div class="container">
  <h1>Accessibility Audit Report</h1>
  <div class="meta">WCAG ${report.wcagLevel} · ${esc(report.timestamp)}</div>

  <div class="summary">
    <div class="stat"><div class="stat-value" style="color:${gradeColor}">${report.grade}</div><div class="stat-label">Grade</div></div>
    <div class="stat"><div class="stat-value">${report.score}%</div><div class="stat-label">Score</div></div>
    <div class="stat"><div class="stat-value">${report.summary.totalPages}</div><div class="stat-label">Pages</div></div>
    <div class="stat"><div class="stat-value" style="color:#f85149">${report.summary.totalViolations}</div><div class="stat-label">Violations</div></div>
    <div class="stat"><div class="stat-value" style="color:#f85149">${report.summary.criticalCount}</div><div class="stat-label">Critical</div></div>
    <div class="stat"><div class="stat-value" style="color:#bc8cff">${report.summary.seriousCount}</div><div class="stat-label">Serious</div></div>
  </div>

  ${pageRows}

  <div class="footer">Generated by a11y-audit-engine · Built by Quvantic</div>
</div>
</body>
</html>`;

  fs.writeFileSync(outputPath, html, 'utf-8');
}
